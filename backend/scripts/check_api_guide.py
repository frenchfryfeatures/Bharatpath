#!/usr/bin/env python3
"""Hold `docs/backend-guide` to the API the app actually serves.

The guide's checklist (`02-api-checklist.md`) said "nothing gets missed" and
missed 33 operations by 2026-10-13, and claimed 209 when the app served 247.
A list kept by hand drifts. So the list is generated from the app's own route
table, and this script says which routes no guide document describes.

    python scripts/check_api_guide.py           # report; exit 1 on a gap
    python scripts/check_api_guide.py --write   # regenerate the checklist tables

"Described" means a topic document (not the checklist itself) names the route
as `METHOD /path` somewhere -- a heading, a table row, a list. Path parameter
names do not matter, and `/{candidate,employer,college}/...` covers all three.

Builds the app, so it needs what `export_openapi.py` needs: run it with
`source .test-env.sh` locally (or the CI environment).
"""

