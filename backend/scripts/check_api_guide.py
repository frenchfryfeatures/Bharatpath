Op = tuple[str, str]


def _norm(path: str) -> str:
    return re.sub(r"\{[^}]*\}", "{}", path.rstrip("/")) or "/"


def served() -> dict[Op, str]:
    """`(method, path) -> summary` for every operation, in registration order,
    paths relative to the API prefix."""
    from app.main import create_app
    from app.settings import get_settings

    prefix = get_settings().api_v1_prefix
    ops: dict[Op, str] = {}
    for path, item in create_app().openapi()["paths"].items():
        for method, op in item.items():
            if method.upper() in METHODS:
                short = path.removeprefix(prefix)
                key = (method.upper(), short)
                ops[key] = SUMMARIES.get(key) or op.get("summary") or ""
    for key, (summary, _flag) in FLAG_GATED.items():
        ops.setdefault(key, summary)
    return ops


def _expand(path: str) -> list[str]:
    """`/{candidate,employer,college}/x` as its three paths."""
    parts = re.split(r"(\{[^{}]*,[^{}]*\})", path)
    choices = [p[1:-1].split(",") if p.startswith("{") and "," in p else [p] for p in parts]
    return ["".join(combo) for combo in itertools.product(*choices)]


def described() -> dict[Op, str]:
    """`(method, normalised path) -> the topic document describing it`.

    A document with the route in a heading or a table row wins over one that
    only mentions it in passing; otherwise the first by number."""
    pattern = re.compile(r"\b(GET|POST|PUT|PATCH|DELETE)[\s|`]+(/[A-Za-z0-9_\-/{},.]+)")
    headed: dict[Op, str] = {}
    mentioned: dict[Op, str] = {}
    for doc in sorted(GUIDE.glob("[0-9][0-9]-*.md")):
        if doc == CHECKLIST:
            continue
        for line in doc.read_text(encoding="utf-8").splitlines():
            where = headed if line.lstrip().startswith(("#", "|")) else mentioned
            for method, raw in pattern.findall(line):
                for path in _expand(raw.rstrip(".,").removeprefix("/api/v1")):
                    where.setdefault((method, _norm(path)), doc.name)
    return {**mentioned, **headed}


def section_of(path: str) -> str | None:
    for title, prefixes in SECTIONS:
        if any(path == p or path.startswith(p + "/") for p in prefixes):
            return title
    return None


def render(ops: dict[Op, str], docs: dict[Op, str]) -> str:
    by_section: dict[str, list[Op]] = {title: [] for title, _ in SECTIONS}
    for op in ops:
        title = section_of(op[1])
        assert title is not None  # `check` refuses an unsectioned route first
        by_section[title].append(op)
    lines = [
        BEGIN,
        "",
        f"**{len(ops)} operations**, every one served by a local build "
        f"(dev-only and flag-gated routes included) — generated from the app's own "
        f"route table on each run, never typed by hand.",
        "",
    ]
    for title, members in by_section.items():
        if not members:
            continue
        lines += [
            f"## {title}",
            "",
            "| Method | Path | What it's for | Guide |",
            "|---|---|---|---|",
        ]
        for method, path in members:
            doc = docs.get((method, _norm(path)))
            link = f"[{doc[:2]}]({doc})" if doc else "**missing**"
            summary = ops[(method, path)].replace("|", "\\|")
            gate = FLAG_GATED.get((method, path))
            if gate:
                summary += f" — only with `{gate[1]}=true`"
            lines.append(f"| {method} | `{path}` | {summary} | {link} |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="Regenerate the checklist tables.")
    args = parser.parse_args()

    ops = served()
    docs = described()
    problems: list[str] = []

    unsectioned = [op for op in ops if section_of(op[1]) is None]
    problems += [f"no checklist section for {m} {p}: add one to SECTIONS" for m, p in unsectioned]
    undescribed = [op for op in ops if (op[0], _norm(op[1])) not in docs]
    problems += [f"no guide document describes {m} {p}" for m, p in undescribed]
    if unsectioned:
        for line in problems:
            print(line)
        return 1

    text = CHECKLIST.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"{CHECKLIST.name} has no generated block; add the {BEGIN!r} markers.")
        return 1
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    fresh = head + render(ops, docs) + tail
    if args.write:
        CHECKLIST.write_text(fresh, encoding="utf-8")
        print(f"Wrote {CHECKLIST.name}: {len(ops)} operations.")
    elif fresh != text:
        problems.append(f"{CHECKLIST.name} is out of date: run with --write")

    for line in problems:
        print(line)
    if not problems:
        print(f"OK - {len(ops)} operations, every one in the checklist and described in the guide.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
